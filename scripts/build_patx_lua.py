# build_patx_lua.py - patx_en.json + patx_chunks_da/*.json -> addon/PatternsX.lua
# PolishForever's English line patterns (matcher) with Danish templates ({1}, {2} = the captured parts). Loaded after Patterns.lua:
# it wraps ns.translatePattern, so the older, hand-made patterns keep priority and these are the fallback.
import os; os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "work"))   # scripts always run with work/ as the working directory
import glob, json, re

TOKEN = re.compile(r"\{\d+\}")
en_items = {e["i"]: e for e in json.load(open("patx_en.json", encoding="utf-8"))}
da = {}
for f in sorted(glob.glob("patx_chunks_da/names_*.json")):
    for x in json.load(open(f, encoding="utf-8")):
        e = en_items.get(x.get("i"))
        t = x.get("da")
        if (e and isinstance(t, str) and t.strip() and sorted(TOKEN.findall(e["tpl"])) == sorted(TOKEN.findall(t))
                and e["tpl"].count("%") == t.count("%") and e["tpl"].count("\n") == t.count("\n")):
            da[e["i"]] = t.strip()

def lit_of(tpl):
    parts = [p for p in TOKEN.split(tpl)]
    return max(parts, key=len)

rows = []
too_many = 0
for i, t in da.items():
    e = en_items[i]
    if max(int(k[1:-1]) for k in TOKEN.findall(e["tpl"])) > 8:        # the engine reads at most 8 captures
        too_many += 1
        continue
    lit = lit_of(e["tpl"])
    first = e["tpl"][0] if not e["tpl"].startswith("{") else ""
    rows.append((len(lit), e["pat"], t, lit, first))
rows.sort(key=lambda r: (-r[0], r[1]))                # most specific first

def q(s):
    return json.dumps(s, ensure_ascii=False)

ENGINE = r'''
-- ---- engine ----
local byFirst, generic = {}, {}
for i = 1, #list do
    local e = list[i]
    local entry = { pat = e[1], da = e[2], lit = e[3] }
    local f = e[4]
    if f == "" then
        generic[#generic + 1] = entry
    else
        byFirst[f] = byFirst[f] or {}
        table.insert(byFirst[f], entry)
    end
end
list = nil

local units = {
    sec = "sek", secs = "sek", second = "sekund", seconds = "sekunder",
    min = "min", mins = "min", minute = "minut", minutes = "minutter",
    hr = "t", hrs = "t", hour = "time", hours = "timer",
    day = "dag", days = "dage",
}

local function capture(c, tr)
    if c:match("^[%d%.,%-%%]+$") then return c end
    local v = tr(c)
    if v ~= c then return v end
    local n, u = c:match("^([%d%.,]+)%s+(%a+)$")
    local du = n and units[u:lower()]
    if du then return n .. " " .. du end
    return c
end

local cache, cached, depth = {}, 0, 0

local function try(list_, text, tr)
    for i = 1, #list_ do
        local p = list_[i]
        if text:find(p.lit, 1, true) then
            local ok, c1, c2, c3, c4, c5, c6, c7, c8 = pcall(string.match, text, p.pat)
            if ok and c1 then
                local caps = { c1, c2, c3, c4, c5, c6, c7, c8 }
                depth = depth + 1
                for k = 1, #caps do caps[k] = capture(caps[k], tr) end
                depth = depth - 1
                return (p.da:gsub("{(%d+)}", function(k) return caps[tonumber(k)] or "" end))
            end
        end
    end
end

local base = ns.translatePattern

function ns.translatePattern(text, tr)
    local r = base and base(text, tr)
    if r then return r end
    if #text < 8 or #text > 600 or depth >= 2 or not text:find("%a%a%a") then return nil end
    local hit = cache[text]
    if hit ~= nil then return hit or nil end
    local result = false
    local b = byFirst[text:sub(1, 1)]
    if b then result = try(b, text, tr) or false end
    if not result then result = try(generic, text, tr) or false end
    cached = cached + 1
    if cached > 3000 then cache, cached = {}, 1 end
    cache[text] = result
    return result or nil
end
'''

with open("addon/PatternsX.lua", "w", encoding="utf-8") as f:
    f.write("local _, ns = ...\n\n-- Tooltip and message line patterns (English Lua pattern, Danish template, longest literal part, first letter).\n")
    f.write("-- Generated by build_patx_lua.py from PolishForever's English patterns (data CC BY 4.0); Danish text is machine-translated.\n")
    f.write("local list = {\n")
    for _, pat, t, lit, first in rows:
        f.write(f"    {{{q(pat)}, {q(t)}, {q(lit)}, {q(first)}}},\n")
    f.write("}\n")
    f.write(ENGINE)
print(len(rows), "of", len(en_items), "patterns written to addon/PatternsX.lua;", len(en_items) - len(da), "without a valid translation;", too_many, "with more than 8 captures")
